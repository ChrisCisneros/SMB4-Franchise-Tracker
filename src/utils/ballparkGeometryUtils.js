export function geometryIdForTeam(team){
  const abbr=String(team?.abbr||'').toUpperCase();
  if(TEAM_BALLPARK_GEOMETRY[abbr])return TEAM_BALLPARK_GEOMETRY[abbr];
  // Expansion/custom clubs still get a stable park shape rather than collapsing to one generic field.
  const ids=Object.keys(BALLPARK_GEOMETRIES);
  const seed=[...abbr].reduce((n,c)=>((n*33)^c.charCodeAt(0))>>>0,5381);
  return ids[seed%ids.length]||'P14';
}

export function getBallparkGeometry(team,overrideId=''){
  const id=BALLPARK_GEOMETRIES[overrideId]?overrideId:geometryIdForTeam(team);
  return BALLPARK_GEOMETRIES[id]||BALLPARK_GEOMETRIES.P14;
}
